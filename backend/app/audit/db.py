"""audit 包的库连接与建表（挂 catalog 库，随 catalog.init() 幂等建表）。"""
from .. import db as dblayer
from ..catalog.db import _conn  # noqa: F401  复用 catalog 连接

# 自增主键方言差异：SQLite AUTOINCREMENT / PG IDENTITY
_ID = ("INTEGER PRIMARY KEY AUTOINCREMENT" if not dblayer.is_pg()
       else "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")


# 审计留痕必须能回答两个问题：这条变更属于哪个租户、对应哪一次请求。
# 没有 tenant_id，多租户上线后审计页会跨租户串数据；
# 没有 request_id，审计记录无法与业务日志对上，排查时两边各说各话。
_EXTRA_COLUMNS = (("tenant_id", "TEXT"), ("request_id", "TEXT"))


def _migrate_columns(con):
    """为老库补列，幂等。"""
    cols = dblayer.table_columns(con, "audit_logs")
    for name, definition in _EXTRA_COLUMNS:
        if name not in cols:
            con.execute(f"ALTER TABLE audit_logs ADD COLUMN {name} {definition}")
    con.commit()


def init_tables(con=None):
    """幂等建表；catalog.init() 传入已建好基础表的连接复用。"""
    own = con is None
    if own:
        con = _conn()
    con.executescript(f"""
    CREATE TABLE IF NOT EXISTS audit_logs(
      id {_ID},
      actor_id TEXT, actor_name TEXT,
      action TEXT, obj_type TEXT, obj_id TEXT,
      before TEXT, after TEXT,
      ip TEXT, created_at TEXT,
      tenant_id TEXT, request_id TEXT);
    CREATE INDEX IF NOT EXISTS idx_audit_logs_obj ON audit_logs(obj_type);
    CREATE INDEX IF NOT EXISTS idx_audit_logs_actor ON audit_logs(actor_id);
    CREATE INDEX IF NOT EXISTS idx_audit_logs_created ON audit_logs(created_at);
    CREATE INDEX IF NOT EXISTS idx_audit_logs_tenant ON audit_logs(tenant_id);
    """)
    con.commit()
    _migrate_columns(con)
    if own:
        con.close()
